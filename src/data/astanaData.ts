export function getChannelEpg(channel: TvChannel): EpgProgram[] {
  const cat = channel.category.toLowerCase();
  if (cat.includes('спорт')) {
    return [
      { time: '16:30', title: 'Обзор КХЛ: матчи Барыса', genre: 'Спорт' },
      { time: '18:00', title: channel.currentShow || 'Прямая трансляция', genre: 'Live', isNow: true },
      { time: '20:15', title: channel.nextShow || 'Аналитика тура', genre: 'Аналитика' },
      { time: '22:00', title: 'Велоспорт и лёгкая атлетика', genre: 'Спорт' },
    ];
  }
  if (cat.includes('дет')) {
    return [
      { time: '16:00', title: 'Алдар Көсе (анимация)', genre: 'Мультфильм' },
      { time: '18:00', title: channel.currentShow || 'Умные сказки', genre: 'Live', isNow: true },
      { time: '19:30', title: channel.nextShow || 'Весёлая математика', genre: 'Обучение' },
      { time: '21:00', title: 'Ертегілер елінде', genre: 'Сказка' },
    ];
  }
  if (cat.includes('культур') || cat.includes('abai')) {
    return [
      { time: '16:45', title: 'Шедевры кюя и домбры', genre: 'Музыка' },
      { time: '18:00', title: channel.currentShow || 'Классика театра', genre: 'Live', isNow: true },
      { time: '20:00', title: channel.nextShow || 'Диалоги о культуре', genre: 'Ток-шоу' },
      { time: '21:45', title: 'Вечерний симфонический концерт', genre: 'Концерт' },
    ];
  }
  return [
    { time: '16:30', title: 'Дневной выпуск новостей', genre: 'Новости' },
    { time: '18:00', title: channel.currentShow || 'Прямой эфир', genre: 'Live', isNow: true },
    { time: '20:00', title: channel.nextShow || 'Итоги дня · Астана', genre: 'Аналитика' },
    { time: '21:30', title: 'Вечерний кинопоказ / Спецпроект', genre: 'Кино' },
  ];
}

